def extract_coordinates_and_values_from_layer(layer, attribute):
    """
    Extracts coordinates and values from an attribute of a QGIS layer.

    Args:
        layer: QGIS QgsVectorLayer
        attribute: name of the attribute to extract

    Returns:
        tuple: (coordinates, values, null_count)
        - coordinates: array of coordinates (n_points, 2) with [x, y]
        - values: array of attribute values (n_points,)
        - null_count: number of null values found
        Returns (None, None, 0) if there is an error or no valid data
    """
    try:
        from qgis.core import QgsVectorLayer
        from qgis.PyQt.QtCore import QVariant

        if not isinstance(layer, QgsVectorLayer):
            return None, None, 0

        field_index = layer.fields().indexOf(attribute)
        if field_index == -1:
            return None, None, 0

        coordinates = []
        values = []
        null_count = 0

        for feature in layer.getFeatures():
            geom = feature.geometry()
            if geom:
                point = geom.asPoint()
                value = feature[attribute]

                # Check if the value is NULL
                if value is None or (isinstance(value, QVariant) and value.isNull()):
                    null_count += 1
                else:
                    try:
                        float_value = float(value)
                        if not np.isnan(float_value) and not np.isinf(float_value):
                            coordinates.append([point.x(), point.y()])
                            values.append(float_value)
                        else:
                            null_count += 1
                    except (ValueError, TypeError):
                        null_count += 1

        if len(coordinates) == 0 or len(values) == 0:
            return None, None, null_count

        return np.array(coordinates), np.array(values), null_count

    except Exception:
        return None, None, 0


def extract_layer_coordinates(layer, include_fids=None):
    """
    Extracts XY coordinates from every point feature in a vector layer.

    Args:
        layer: QgsVectorLayer with point geometries.
        include_fids: optional set of feature IDs to keep; None keeps all.

    Returns:
        ndarray of shape (n_points, 2), or None when the layer is invalid
        or contains no point geometries.
    """
    try:
        from qgis.core import QgsVectorLayer

        if not isinstance(layer, QgsVectorLayer):
            return None

        coordinates = []
        for feature in layer.getFeatures():
            if include_fids is not None and feature.id() not in include_fids:
                continue
            geom = feature.geometry()
            if not geom or geom.isEmpty():
                continue
            point = geom.asPoint()
            coordinates.append([point.x(), point.y()])

        if not coordinates:
            return None
        return np.asarray(coordinates, dtype=float)
    except Exception:
        return None


def apply_value_transform(values, transform='none'):
    """
    Applies a transformation to an array of values.

    Args:
        values: array-like of numeric values
        transform: 'none' or 'log'

    Returns:
        tuple: (transformed_values, excluded_non_positive, error_message)
        error_message is None on success; transformed_values is None on error
    """
    values = np.asarray(values, dtype=float)
    if transform in ('none', 0):
        return values, 0, None

    if transform in ('log', 1):
        positive_mask = values > 0
        excluded = int(np.sum(~positive_mask))
        positive_values = values[positive_mask]
        if positive_values.size == 0:
            return None, excluded, (
                "There are no positive values for the Log transformation."
            )
        return np.log(positive_values), excluded, None

    return values, 0, None


def align_coordinates_with_transform(coordinates, values, transform='none'):
    """
    Returns coordinates and values aligned after applying the same rules
    as apply_value_transform (e.g. log keeps only points with value > 0).

    Returns:
        tuple: (coordinates, transformed_values, excluded_non_positive, error_message)
    """
    coordinates = np.asarray(coordinates, dtype=float)
    values = np.asarray(values, dtype=float)
    transformed, excluded, error = apply_value_transform(values, transform)
    if error:
        return None, None, excluded, error
    if transform in ('none', 0):
        return coordinates, transformed, excluded, None
    positive_mask = values > 0
    return coordinates[positive_mask], transformed, excluded, None


def compute_descriptive_stats(values):
    """
    Computes descriptive statistics for a numeric array.

    Returns:
        dict with keys from STAT_KEYS, or None if there are no valid values
    """
    values = np.asarray(values, dtype=float)
    if values.size == 0:
        return None

    n = values.size
    result = {
        'count': n,
        'min': float(np.min(values)),
        'max': float(np.max(values)),
        'mean': float(np.mean(values)),
        'median': float(np.median(values)),
    }

    if n > 1:
        result['std'] = float(np.std(values, ddof=1))
        result['variance'] = float(np.var(values, ddof=1))
    else:
        result['std'] = float('nan')
        result['variance'] = float('nan')

    if n > 2:
        result['asymmetry'] = float(stats.skew(values, bias=False))
        result['kurtosis'] = float(stats.kurtosis(values, bias=False))
    else:
        result['asymmetry'] = float('nan')
        result['kurtosis'] = float('nan')

    return result


def resolve_point_id_field(layer, attribute):
    """
    Picks a layer field to use as point ID in cross-validation tables.

    Prefers common identifier field names; skips the analysis attribute.
    Returns None when no dedicated ID field is found (fid is used).
    """
    from qgis.core import QgsVectorLayer

    if not isinstance(layer, QgsVectorLayer):
        return None

    attr_lower = attribute.lower()
    for field in layer.fields():
        name = field.name() #Get the name of the attribute header
        QgsMessageLog.logMessage("Attribute header to evaluate as ID for the wells: " + field.name(), "ID Field") #Debugging

        #If the attribute header is the same as the attribute to evaluate as ID, skip it
        if name.lower() == attr_lower:
            continue

        lower = name.lower() #Convert the name of the attribute header to lowercase
        if lower in _ID_FIELD_HINTS:# or lower.endswith('id') or lower.endswith('cve'):
            QgsMessageLog.logMessage("Attribute to be used as ID for the wells: " + name, "ID Field") #Debugging
            return name #Return the name of the attribute header to be used as ID for the wells
    QgsMessageLog.logMessage("No attribute header found to be used as ID for the wells, defaulting to fid", "ID Field") #Debugging
    return None #Return None if no attribute header is found to be used as ID for the wells (fid used instead)


def resolve_well_weight_field(layer, attribute):
    """
    Picks a layer field to use as per-well weight during prioritization.

    Matches common weight column names (same keywords as geostat_app_kalman_v10).
    Skips the analysis attribute and ID-like fields.
    """
    from qgis.core import QgsVectorLayer

    if not isinstance(layer, QgsVectorLayer):
        return None

    attr_lower = attribute.lower()
    for field in layer.fields():
        name = field.name()
        lower = name.lower().strip()
        if lower == attr_lower:
            continue
        if lower in _ID_FIELD_HINTS or lower.endswith('id') or lower.endswith('cve'):
            continue
        if lower in _WELL_WEIGHT_FIELD_HINTS:
            return name
    return None


def _sanitize_well_weights(weights):
    """Ensures well weights are positive (non-positive values are replaced)."""
    weights = np.asarray(weights, dtype=float)
    if weights.size == 0:
        return weights
    positive = weights[weights > 0]
    fallback = float(np.min(positive)) if positive.size > 0 else 1.0
    return np.where(weights > 0, weights, fallback)


def extract_point_records_from_layer(
    layer, attribute, id_field=None, weight_field=None, include_fids=None
):
    """
    Extracts point IDs, coordinates, values and optional well weights.

    Args:
        include_fids: optional set of feature IDs to keep; None keeps all.
            Unchecked wells on Tab 1 are excluded before null/value filtering.

    Returns:
        tuple: (point_ids, coordinates, values, null_count, well_weights)
        well_weights are 1.0 when no weight field is available.
    """
    try:
        from qgis.core import QgsVectorLayer
        from qgis.PyQt.QtCore import QVariant

        if not isinstance(layer, QgsVectorLayer):
            return None, None, None, 0, None

        field_index = layer.fields().indexOf(attribute)
        if field_index == -1:
            return None, None, None, 0, None

        if id_field is None:
            id_field = resolve_point_id_field(layer, attribute)
        id_index = layer.fields().indexOf(id_field) if id_field else -1

        if weight_field is None:
            weight_field = resolve_well_weight_field(layer, attribute)
        weight_index = layer.fields().indexOf(weight_field) if weight_field else -1

        point_ids = []
        coordinates = []
        values = []
        well_weights = []
        null_count = 0

        for feature in layer.getFeatures():
            if include_fids is not None and feature.id() not in include_fids:
                continue

            geom = feature.geometry()
            if not geom:
                continue

            point = geom.asPoint()
            value = feature[attribute]

            if value is None or (isinstance(value, QVariant) and value.isNull()):
                null_count += 1
                continue

            try:
                float_value = float(value)
                if np.isnan(float_value) or np.isinf(float_value):
                    null_count += 1
                    continue
            except (ValueError, TypeError):
                null_count += 1
                continue

            if id_index >= 0:
                raw_id = feature[id_field]
                if raw_id is None or (
                    isinstance(raw_id, QVariant) and raw_id.isNull()
                ):
                    point_id = str(feature.id())
                else:
                    point_id = str(raw_id)
            else:
                point_id = str(feature.id())

            weight = 1.0
            if weight_index >= 0:
                raw_weight = feature[weight_field]
                if raw_weight is not None and not (
                    isinstance(raw_weight, QVariant) and raw_weight.isNull()
                ):
                    try:
                        weight = float(raw_weight)
                    except (ValueError, TypeError):
                        weight = 1.0

            point_ids.append(point_id)
            coordinates.append([point.x(), point.y()])
            values.append(float_value)
            well_weights.append(weight)

        if not point_ids:
            return None, None, None, null_count, None

        return (
            np.array(point_ids, dtype=object),
            np.array(coordinates),
            np.array(values),
            null_count,
            _sanitize_well_weights(np.array(well_weights)),
        )
    except Exception:
        return None, None, None, 0, None


def build_point_id_layer_attribute_map(layer, attribute, include_fids=None):
    """
    Map point ID strings to full layer attribute dicts for valid analysis points.

    Uses the same point-ID assignment and attribute validity rules as
    ``extract_point_records_from_layer`` so export rows align with optimization.

    Args:
        include_fids: optional set of feature IDs to keep; None keeps all.

    Returns:
        tuple: (field_names, records_by_point_id)
            field_names: layer field names in QgsFields order.
            records_by_point_id: dict mapping point_id str -> {field: raw value}.
        Returns ([], {}) when the layer or attribute is invalid.
    """
    try:
        from qgis.core import QgsVectorLayer
        from qgis.PyQt.QtCore import QVariant

        if not isinstance(layer, QgsVectorLayer):
            return [], {}

        fields = layer.fields()
        field_names = [field.name() for field in fields]
        if not field_names:
            return [], {}

        field_index = fields.indexOf(attribute)
        if field_index == -1:
            return [], {}

        id_field = resolve_point_id_field(layer, attribute)
        id_index = fields.indexOf(id_field) if id_field else -1

        records_by_point_id = {}
        for feature in layer.getFeatures():
            if include_fids is not None and feature.id() not in include_fids:
                continue
            if not feature.geometry():
                continue

            value = feature[attribute]
            if value is None or (isinstance(value, QVariant) and value.isNull()):
                continue

            try:
                float_value = float(value)
                if np.isnan(float_value) or np.isinf(float_value):
                    continue
            except (ValueError, TypeError):
                continue

            if id_index >= 0:
                raw_id = feature[id_field]
                if raw_id is None or (
                    isinstance(raw_id, QVariant) and raw_id.isNull()
                ):
                    point_id = str(feature.id())
                else:
                    point_id = str(raw_id)
            else:
                point_id = str(feature.id())

            records_by_point_id[point_id] = {
                name: feature[name] for name in field_names
            }

        return field_names, records_by_point_id
    except Exception:
        return [], {}


