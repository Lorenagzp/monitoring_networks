    def _update_cross_validation(
        self, coordinates, values, point_ids, attr_name
    ):
        """
        Runs leave-one-out CV with the fitted variogram and refreshes tab 2 UI.

        Uses ordinary kriging: each point is predicted from all other points
        using the current variogram model parameters for the active attribute.
        """
        state = self._get_variogram_state(attr_name)
        if state is None:
            self._clear_cross_validation()
            return

        try:
            cv_result = run_leave_one_out_cross_validation(
                coordinates,
                values,
                state.get('model_type', 'spherical'),
                state.get('nugget', 0),
                state.get('sill', 0),
                state.get('range', 0),
            )
        except Exception:
            self._clear_cross_validation()
            self.cv_info_label.setText(
                QCoreApplication.translate(
                    "Tab 2",
                    "Cross-validation could not be completed.",
                )
            )
            self.cv_info_label.setStyleSheet("color: red; font-style: italic;")
            return

        if cv_result is None:
            self._clear_cross_validation()
            self.cv_info_label.setText(
                QCoreApplication.translate(
                    "Tab 2",
                    "At least three points are required for cross-validation.",
                )
            )
            self.cv_info_label.setStyleSheet("color: red; font-style: italic;")
            return

        summary = cv_result['summary']
        rows = cv_result['rows']
        self._populate_cross_validation_summary(summary)
        self._populate_cross_validation_results(point_ids, rows)

        measured = [row['measured'] for row in rows]
        predicted = [row['predicted'] for row in rows]
        self._update_cross_validation_plot(measured, predicted, attr_name)

        self.cv_info_label.setText(
            QCoreApplication.translate(
                "Tab 2",
                "Leave-one-out cross-validation for «{param}» ({n} points).",
            ).format(param=attr_name, n=len(rows))
        )
        self.cv_info_label.setStyleSheet("color: gray; font-style: italic;")

