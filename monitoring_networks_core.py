import os
from PyQt5.QtWidgets import QAction
from PyQt5.QtGui import QIcon
from qgis.PyQt.QtCore import QSettings, QTranslator, QCoreApplication, Qt
from qgis.core import QgsMessageLog


class MonitoringNetworks:
    def __init__(self, iface):
        self.iface = iface
        self.plugin_dir = os.path.dirname(__file__)
        # Strong refs so multiple open windows are not garbage-collected.
        self.dialogs = []
        self.actions = []
        self.menu = "&MonitoringNetworks"
        self.toolbar = self.iface.addToolBar("MonitoringNetworks")

        # Regarding the translation
        plugin_dir = os.path.dirname(__file__)
        locale = QSettings().value("locale/userLocale","en")[0:2]
        localePath = os.path.join(
            plugin_dir, 'i18n', f'monitoring_networks_{locale}.qm'
        ) #Path to search the translation, based on the QGIS/system language
        QgsMessageLog.logMessage("Locale path: " + localePath, "Loading Pugin") #Message to user

        if os.path.exists(localePath):
            QgsMessageLog.logMessage("Translation found for: " + localePath) #Message to user
            self.translator = QTranslator()
            if self.translator.load(localePath):
                QCoreApplication.installTranslator(self.translator)
            else:
                QgsMessageLog.logMessage("Translator was not installed.", "Loading Pugin") #Message to user

    def add_action(self, icon_path, text, callback, parent=None):
        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        self.toolbar.addAction(action)
        self.iface.addPluginToMenu(self.menu, action)
        self.actions.append(action)
        return action

    def initGui(self):
        icon_path = os.path.join(self.plugin_dir, 'icon.png')
        if not os.path.exists(icon_path):
            icon_path = ':/plugins/gmonitoring_networks/icon.png'

        self.add_action(
            icon_path,
            text="MonitoringNetworks",
            callback=self.run,
            parent=self.iface.mainWindow()
        )

    def _forget_dialog(self, dialog):
        """Drop a closed dialog from the live-window list."""
        try:
            self.dialogs.remove(dialog)
        except ValueError:
            pass

    def unload(self):
        for dialog in list(self.dialogs):
            dialog.close()
        self.dialogs.clear()

        for action in self.actions:
            self.iface.removePluginMenu(self.menu, action)
            self.iface.removeToolBarIcon(action)
        del self.toolbar

    def run(self):
        """Open a fresh independent dialog window (one per toolbar click)."""
        from .monitoring_networks_dialog import MonitoringNetworksDialog

        dialog = MonitoringNetworksDialog(self.iface)
        dialog.setAttribute(Qt.WA_DeleteOnClose, True)
        dialog.finished.connect(lambda _result, d=dialog: self._forget_dialog(d))
        self.dialogs.append(dialog)
        dialog.show()
        dialog.raise_()
        dialog.activateWindow()
